"""指令词表的**单一来源**。

为什么单独抽一个文件
--------------------
指令前缀同时被三方使用：技能插件（应答）、拓展插件（应答）、路由插件（兜底与跨方言检索）。
如果三处各写一份字面量，改动时必然漏掉一处 —— 而漏掉的那处会表现为
「某个方言突然查不到」，排查成本极高。所以只允许在这里定义。

作用域规则（这是 13 个方言插件能共存的关键）
-------------------------------------------
`text.pre` 是**链式**的：值依次流经各处理器，谁先跑谁就能改写文本。
插件注册表的排序是 `priority 降序，同优先级按 id 升序` ——
如果 13 个方言插件都认「翻译：」这个裸指令，那么 id 最小的那个会抢答一切查询、
对它不认识的词回「未收录」并把指令从文本里剥掉，其余 12 个永远轮不到。
（这是实测踩到的坑，不是推测。）

因此：
  - **各方言插件只认带自己简称的指令** —— `<short>翻译：X`、`<short>语法：T` 等。
    这类指令天然唯一，不会互相截胡。
  - **裸指令（`翻译：X`、`俗语：X`）交给跑在最后的「路由插件」** ——
    它跨全部方言词表检索，答案里同时给出命中的方言简称，
    并提示用户可用 `<short>翻译：X` 定向查询。
  - 路由插件同时是**兜底**：某个方言插件被停用或启动失败时，它的作用域指令
    不会被任何插件消费，此时由路由插件直接读词表作答。
"""

# 技能插件：动词 -> 用途
SKILL_VERBS = ("翻译", "怎么说", "语法")
# 拓展插件：动词 —— 恰好等于条目 type
EXTRA_VERBS = ("俗语", "歇后语", "童谣", "民俗")
# 条目 type 取值（与拓展表 entries[].type 一致）
EXTRA_TYPES = set(EXTRA_VERBS)

COLONS = ("：", ":")            # 中英文冒号都接受

# 路由器要认的动词集合（带简称与裸指令都按这个全集来匹配）
# 注意：必须由 SKILL_VERBS 派生而不是手写字面量 —— 第一版手写成
# ("翻译", "怎么说") + EXTRA_VERBS，漏掉了「语法」，于是裸「语法：入声」无人应答。
BARE_VERBS = SKILL_VERBS + EXTRA_VERBS


def scoped_prefix(short, verb, colon="："):
    """构造带方言简称的指令前缀，如 粤语 + 翻译 -> 「粤语翻译：」。"""
    return "%s%s%s" % (short, verb, colon)


def match_command(line, prefix):
    """判断行首是否为该指令（中英文冒号都算），是则返回去除指令后的词条，否则 None。"""
    for colon in COLONS:
        full = prefix[:-1] + colon if prefix.endswith(tuple(COLONS)) else prefix + colon
        if line.startswith(full):
            return line[len(full):].strip()
    return None
