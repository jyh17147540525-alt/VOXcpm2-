"""清唱生成插件（clear vocal）
==============================
把一首歌的伴奏剥离、只保留旋律骨架，再用指定音色重新唱出来。

模块划分（数据流自上而下）
--------------------------
    audio/music.wav
          │
          ▼
    ┌─────────────┐  MDX 人声分离（voice_clone/mdx_separator）
    │  stems      │  → vocals.wav / instrumental.wav
    └─────────────┘
          │  ⚠️ 必须分析分离后的音轨，不能吃原混音（持续音会污染 onset 包络）
          ▼
    ┌─────────────┐  BPM / 拍点 / F0 / 音符序列 / 调式
    │ analyzer.py │  → {rhythm, notes, key}
    └─────────────┘
          │
          ▼
    ┌─────────────┐  歌词 ↔ 音符的对应 + 逐音目标时长/音高/力度
    │ planner.py  │  → note_plan.json   ← ⭐ 唯一的人工可校正产物
    └─────────────┘
          │
          ▼
    ┌─────────────┐  逐音短句合成（指定音色）
    │ singer.py   │  → [clip_0, clip_1, ...]   ⚠️ 必须在 _infer_lock 之外调用
    └─────────────┘
          │
          ▼
    ┌─────────────┐  拉伸到目标时长 + 搬移到目标音高 + 网格吸附 + 拼接
    │ aligner.py  │  → clear_vocal.wav
    └─────────────┘
          │
          ▼
    ┌─────────────┐  编排、缓存、进展上报、失败降级
    │ plugin.py   │
    └─────────────┘

分层原则
--------
* ``dsp.py`` / ``analyzer.py`` / ``aligner.py`` —— **纯计算**，不依赖模型、
  不依赖插件子系统，可脱离服务单独跑测试。
* ``syllabify.py`` —— 纯文本（代替不可靠的 whisper 词边界，见下）。
* ``singer.py`` —— **唯一**接触 VoxCPM2 模型的模块。
* ``planner.py`` —— 纯数据变换（音符 ↔ 歌词 ↔ JSON），零音频处理。
* ``plugin.py`` —— 编排与胶水层，负责把上面几块接进插件钩子体系。

这样分的目的是让"最难调的那部分"（对齐精度）能在一个不加载模型、
不启服务的进程里被完整断言 —— 见 ``tests/test_clear_vocal_plugin.py``。

⚠️ 两条不可违反的约束
--------------------
1. **合成只能在钩子之外**。``server._infer_lock`` 是非可重入 ``threading.Lock``，
   钩子内回调 ``singer`` 会永久死锁且无任何报错。``singer`` 内置快速失败守卫。
2. **零插件 = 行为逐字节不变**。``plugin.json`` 里 ``enabled=false``，
   且本插件的钩子处理器**只读**状态、绝不触发生成。

关于歌词切分
------------
不用 whisper 的词边界：实测歌声/哼唱只会被转写成 ``'嗯'``（无语义），
且中文切分**不稳定**（同一句"你好啊"一次 3 段、一次 2 段）。
故改为整句文本 + ``syllabify`` 自建切分，保证同一输入永远得到同一结果。

**但 whisper 的文字本身是准的** —— 所以 ``plugin.transcribe_lyric`` 只取
"整句文字"（丢掉词级时间戳），把它喂给 ``syllabify``。这样既拿到了
whisper 的强项（识别文字），又避开了它的弱项（中文切分/时间戳）。
该能力由 ``auto_lyric=True`` 显式开启，默认关闭（它会阻塞请求线程）。

v1 的边界（说清楚，免得被误当成"能唱准任何曲子"）
------------------------------------------------
``synthesize_stable(...)`` **不接受音高/时长/节奏任何输入** —— 这是上游模型
接口的硬边界，不是本插件实现不到位。因此"旋律与原曲完全一致"是通过
**事后 DSP** 逼近的：

* **时长/节奏**：``aligner`` 逐音符拉伸到目标采样点，误差 **0 采样**（真对齐）。
* **音高**：``dsp.pitch_shift`` 在**频域做 bin 重映射 + 相位推进**，不改采样率
  → 共振峰不随基频缩放，故**没有"12 半音音质悬崖"**。
* **音色**：全程复用同一个参考音频，且用**整体八度折叠**把搬移量压到最小。

真正的"把旋律注入模型"需要改 ``voxcpm.core._generate`` 做频域音高条件化，
属于下一步（Phase 2），不在本插件范围内。
"""

